const pins = (g: GameScene): number => ['pin1', 'pin2', 'pin3'].filter((k) => g.flag(k)).length

function objective(g: GameScene): void {
  if (pins(g) < 3) g.setObjective(`Закрепи 3 добрых комментария, чтобы успокоить тред (${pins(g)}/3)`)
  else if (!g.flag('king')) g.setObjective('Победи Короля Ратио')
  else if (!g.flag('petya')) g.setObjective('Найди, кто управляет бот-фермой хейтеров')
  else g.setObjective('Свайп-портал — в левом верхнем углу ветки')
}

