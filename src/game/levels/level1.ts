const likeCount = (g: GameScene): number => ['like1', 'like2', 'like3'].filter((k) => g.flag(k)).length

function objective(g: GameScene): void {
  if (!g.flag('valera')) g.setObjective('Выйди на улицу и найди проход вниз')
  else if (likeCount(g) < 3) g.setObjective(`Поставь 3 лайка на Площади вовлечённости (${likeCount(g)}/3)`)
  else g.setObjective('Свайп-портал за воротами слева внизу')
}

